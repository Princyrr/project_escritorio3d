export function normalizeBrazilState(value: string | null | undefined): string | null {
  if (!value) return null;
  const normalized = value
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase();
  const state = BRAZIL_STATES.find((item) =>
    item.sigla === normalized ||
    item.nome.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toUpperCase() === normalized
  );
  if (state) return state.sigla;

  const ufToken = normalized.match(/(?:^|[^A-Z])([A-Z]{2})(?:$|[^A-Z])/);
  return BRAZIL_STATES.find((item) => item.sigla === ufToken?.[1])?.sigla ?? null;
}

